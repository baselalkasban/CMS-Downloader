# Generates extension/themes.css and extension/lib/themes.js from one table.
import json, sys
out = sys.argv[1]
DARK_TYPES = dict(red='#f87171', orange='#fb923c', amber='#fbbf24', green='#4ade80', teal='#2dd4bf', blue='#60a5fa', purple='#c084fc', gray='#a1a1aa')
LIGHT_TYPES = dict(red='#dc2626', orange='#ea580c', amber='#b45309', green='#16a34a', teal='#0d9488', blue='#2563eb', purple='#9333ea', gray='#6b7280')
T = [
  # id, name, description, dark, bg, surface, surface2, surface3, border, text, text2, muted, faint, accent, accentText, sidebar
  ('midnight', 'Midnight Amber', 'Dark graphite with a warm amber accent', True,
   '#0f0f11', '#17171a', '#1f1f23', '#2a2a30', '#2c2c33', '#ececf1', '#d4d4dc', '#9b9ba6', '#6d6d78', '#f5b301', '#1a1400', '#121214'),
  ('ocean', 'Ocean Depths', 'Deep navy with teal and seafoam', True,
   '#0f1722', '#162131', '#1c293b', '#253549', '#253447', '#f1faee', '#d3e4e6', '#a8bfc4', '#6f8792', '#45b5b5', '#04201f', '#111b28'),
  ('galaxy', 'Midnight Galaxy', 'Deep purple with soft lavender', True,
   '#141020', '#1d1730', '#251e3c', '#2f2749', '#30284a', '#ece9fb', '#d6d1ee', '#a8a0c8', '#77709a', '#a490c2', '#1a1230', '#17122a'),
  ('tech', 'Tech Innovation', 'Near-black with electric blue', True,
   '#0d0d0f', '#161618', '#1e1e21', '#28282c', '#2a2a2f', '#f5f5f7', '#d8d8de', '#9d9da6', '#6b6b74', '#2f80ff', '#ffffff', '#111113'),
  ('forest', 'Forest Canopy', 'Dark green with olive and ivory', True,
   '#10160f', '#172016', '#1e291d', '#283526', '#283427', '#faf9f6', '#dfe3d6', '#a9b19c', '#768067', '#a4ac86', '#151b10', '#131a12'),
  ('arctic', 'Arctic Frost', 'Crisp white with steel blue', False,
   '#f2f6fb', '#ffffff', '#eef3f9', '#e1e9f3', '#d8e2ee', '#1b2735', '#2c3a4b', '#5b6b7d', '#8796a8', '#4a6fa5', '#ffffff', '#e6eef8'),
  ('minimal', 'Modern Minimalist', 'Clean grays with charcoal', False,
   '#f4f5f6', '#ffffff', '#f0f1f3', '#e4e6e9', '#dcdfe3', '#23292e', '#36454f', '#66737d', '#93a0a9', '#36454f', '#ffffff', '#ffffff'),
  ('botanical', 'Botanical Garden', 'Warm cream with fern green', False,
   '#f5f3ed', '#fffdf8', '#f1eee5', '#e7e2d5', '#e2dccd', '#24301f', '#3a4634', '#6a7462', '#98a08e', '#4a7c59', '#ffffff', '#ece8dc'),
]
css = ['/* Generated by themes.py: one block of color tokens per theme. Midnight Amber is the default. */']
js = []
for (tid, name, desc, dark, bg, s1, s2, s3, border, text, text2, muted, faint, accent, acc_text, sidebar) in T:
    types = DARK_TYPES if dark else LIGHT_TYPES
    sel = ':root, :root[data-cmsv-theme="midnight"]' if tid == 'midnight' else f':root[data-cmsv-theme="{tid}"]'
    tokens = {
        'scheme': 'dark' if dark else 'light',
        'bg': bg, 'surface': s1, 'surface-2': s2, 'surface-3': s3, 'border': border,
        'text': text, 'text-2': text2, 'muted': muted, 'faint': faint, 'strong': '#ffffff' if dark else '#0b1118',
        'accent': accent, 'accent-text': acc_text,
        'accent-soft': f'color-mix(in srgb, {accent} {14 if dark else 12}%, transparent)',
        'note-text': f'color-mix(in srgb, {accent} {55 if dark else 70}%, {text})',
        'glass': f'color-mix(in srgb, {s1} 96%, transparent)',
        'shadow': '0 10px 30px rgba(0, 0, 0, .3)' if dark else '0 8px 24px rgba(20, 30, 50, .08)',
        'star-off': f'color-mix(in srgb, {muted} 45%, {s1})',
        'viewer-bg': '#202124' if dark else '#e9ecef',
        'sidebar': sidebar, 'radius': '14px',
        **{f'c-{k}': v for k, v in types.items()},
    }
    body = '\n'.join(f'  --cv-{k}: {v};' for k, v in tokens.items())
    css.append(f'{sel} {{\n{body}\n}}')
    js.append(dict(id=tid, name=name, description=desc, dark=dark, swatch=[bg, s2, accent]))
open(f'{out}/themes.css', 'w').write('\n\n'.join(css) + '\n')
open(f'{out}/lib/themes.js', 'w').write(
    '// Generated by themes.py: the themes users can pick (colors live in themes.css).\n'
    f'var CMSThemes = {json.dumps(js, indent=2)};\n')
print('ok', len(T))
